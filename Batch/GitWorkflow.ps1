param([ValidateSet('Menu','Check','Pull','CommitPush','Push','PullCommitPush','PreviewMessage')][string]$Action = 'Menu')
$ErrorActionPreference = 'Stop'
[Console]::InputEncoding = [Text.UTF8Encoding]::new($false)
[Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)
$OutputEncoding = [Console]::OutputEncoding
function Invoke-Git([string[]]$GitArgs) {
    & git @GitArgs | Out-Host
    if ($LASTEXITCODE -ne 0) { throw "Git failed (exit $LASTEXITCODE): $($GitArgs[0]). Local changes and commits are preserved." }
}
function Read-Git([string[]]$GitArgs) {
    $result = & git @GitArgs
    if ($LASTEXITCODE -ne 0) { throw "Git failed: $($GitArgs[0]). Check repository/upstream configuration." }
    return $result
}
function New-StagedCommitMessage {
    $files = @(Read-Git @('-c','core.quotepath=false','diff','--cached','--name-only','--no-renames'))
    if ($files.Count -eq 0) { throw 'No staged changes available for message generation.' }
    # Prefer implementation files over generated history when choosing the subject.
    $primary = @($files | Where-Object { $_ -notmatch '^(History/|MD/)' })
    if ($primary.Count -eq 0) { $primary = $files }
    $label = [IO.Path]::GetFileName($primary[0])
    if ($label.Length -gt 45) { $label = $label.Substring(0,42) + '...' }
    $title = "Update $label"
    if ($files.Count -gt 1) { $title += " and $($files.Count - 1) other files" }
    $status = @(Read-Git @('-c','core.quotepath=false','diff','--cached','--name-status','--no-renames'))
    $stats = @(Read-Git @('-c','core.quotepath=false','diff','--cached','--numstat','--no-renames'))
    $summary = @(Read-Git @('diff','--cached','--shortstat'))
    $description = @(
        'Changes (generated from staged Git metadata):'
        'A = added, M = modified, D = deleted; renames are listed as delete/add.'
        ($status -join "`r`n")
        ''
        'Line changes (added / removed / path; - means binary):'
        ($stats -join "`r`n")
        ''
        ($summary -join "`r`n")
        ''
        'Validation: not run by this script. Task intent and runtime behavior are not inferred.'
    ) -join "`r`n"
    return "$title`r`n`r`n$description`r`n"
}
function Test-StagedChanges {
    # Whitespace generated by Unity YAML is not a commit blocker.
    # Keep Git's conflict-marker detection and command failures fatal.
    Invoke-Git @('-c','core.whitespace=-blank-at-eol,-blank-at-eof,-space-before-tab,-indent-with-non-tab,-tab-in-indent','diff','--cached','--check')
    & git diff --cached --check | Out-Host
    $checkExit = $LASTEXITCODE
    if ($checkExit -eq 2) {
        Write-Warning 'Whitespace warnings found. Continuing commit; conflict-marker check already passed.'
    } elseif ($checkExit -ne 0) {
        throw "Staged whitespace check failed (exit $checkExit)."
    }
}
function Stage-AllChanges {
    Write-Host 'Automatically staging all non-ignored changes, including new and deleted files.'
    Invoke-Git @('add','--all','--','.')
    if (-not (Read-Git @('diff','--cached','--name-only'))) { Write-Host 'No local changes to stage. Continuing synchronization.'; return }
    Invoke-Git @('diff','--cached','--stat')
}
function Push-Reviewed {
    Invoke-Git @('fetch','--',$script:remote)
    $behind = [int](Read-Git @('rev-list','--count',"HEAD..$script:upstream"))
    if ($behind -gt 0) { throw 'Remote has commits not in HEAD. Push stopped. Resolve separately; no automatic pull/rebase.' }
    $ahead = [int](Read-Git @('rev-list','--count',"$script:upstream..HEAD"))
    if ($ahead -eq 0) { Write-Host 'Nothing to push.'; return }
    Write-Host "ALL $ahead outgoing commits will be pushed to $script:remote / $script:branch."
    Invoke-Git @('--no-pager','log','--stat',"$script:upstream..HEAD")
    Write-Host 'Outgoing changes include earlier local commits, if any.'
    Write-Host "Inspect details separately with: git diff $script:upstream HEAD"
    Write-Host 'Pushing all listed outgoing commits automatically.'
    Invoke-Git @('push','--',$script:remote,"HEAD:refs/heads/$script:branch")
}
try {
    $projectRoot = Split-Path -Parent $PSScriptRoot
    Set-Location -LiteralPath $projectRoot
    if (-not (Get-Command git -ErrorAction SilentlyContinue)) { throw 'Install Git for Windows and reopen the terminal.' }
    $root = Read-Git @('rev-parse','--show-toplevel')
    if ([IO.Path]::GetFullPath($root) -ne [IO.Path]::GetFullPath($projectRoot)) { throw 'Place both helper files in the Batch folder directly under the Git repository root.' }
    $branch = Read-Git @('branch','--show-current')
    if (-not $branch) { throw 'Detached HEAD is not supported.' }
    $upstream = Read-Git @('rev-parse','--abbrev-ref','@{upstream}')
    $remote = Read-Git @('config',"branch.$branch.remote")
    $merge = Read-Git @('config',"branch.$branch.merge")
    if ($remote -eq '.' -or $merge -ne "refs/heads/$branch") { throw 'A remote upstream with the same branch name is required. No configuration was changed.' }
    Write-Host "Repository: $root`nBranch: $branch`nUpstream: $upstream"
    Invoke-Git @('status','--short')
    if ($Action -eq 'Check') { Write-Host 'Read-only check completed. No fetch/pull/stage/commit/push performed.'; exit 0 }
    if ($Action -eq 'PreviewMessage') { Write-Host (New-StagedCommitMessage); exit 0 }
    if ($Action -eq 'Menu') {
        Write-Host '1. Pull (clean working tree, fast-forward only)'
        Write-Host '2. Auto Add all changes, Commit with automatic Title + Description, then Push'
        Write-Host '3. Push existing local commits (retry after a failed push)'
        switch (Read-Host 'Choose 1, 2, 3 (anything else exits)') {
            '1' { $Action = 'Pull' }
            '2' { $Action = 'CommitPush' }
            '3' { $Action = 'Push' }
            default { exit 0 }
        }
    }
    if ($Action -in @('CommitPush','PullCommitPush')) {
        Stage-AllChanges
    }
    if ($Action -eq 'PullCommitPush') {
        Write-Host 'Step 1/3: Pull (fast-forward only, no automatic stash).'
        Invoke-Git @('-c','merge.autostash=false','-c','rebase.autostash=false','pull','--ff-only','--no-rebase','--',$remote,$branch)
        Write-Host 'Step 2/3: Commit staged changes. Push follows only after a successful commit.'
        $Action = 'CommitPush'
    }
    if ($Action -eq 'Pull') {
        if (Read-Git @('status','--porcelain')) { throw 'Uncommitted/untracked changes exist. Commit or handle them yourself before Pull. No stash or reset was performed.' }
        Invoke-Git @('-c','merge.autostash=false','-c','rebase.autostash=false','pull','--ff-only','--no-rebase','--',$remote,$branch)
    } elseif ($Action -eq 'CommitPush') {
        if (-not (Read-Git @('diff','--cached','--name-only'))) { Write-Host 'No changes to commit. Checking existing outgoing commits.'; Push-Reviewed; exit 0 }
        Test-StagedChanges
        Invoke-Git @('diff','--cached','--stat')
        $message = New-StagedCommitMessage
        Write-Host "`n$message"
        Write-Host 'The staged changes listed above will be committed with this generated message.'
        Write-Host 'Creating the commit automatically.'
        $messageFile = [IO.Path]::GetTempFileName()
        try {
            [IO.File]::WriteAllText($messageFile,$message,[Text.UTF8Encoding]::new($false))
            Invoke-Git @('-c','i18n.commitEncoding=UTF-8','commit','--cleanup=verbatim','--file',$messageFile)
        } finally { Remove-Item -LiteralPath $messageFile -ErrorAction SilentlyContinue }
        Write-Host 'Commit created locally. If Push fails, use the Push option to retry without another commit.'
        Push-Reviewed
    } else { Push-Reviewed }
    Write-Host 'Completed.'
    exit 0
} catch {
    Write-Host "ERROR: $($_.Exception.Message)" -ForegroundColor Red
    exit 1
}
